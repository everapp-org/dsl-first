using Antlr4.Runtime;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Everapp.Generator;

/// <summary>
/// Derives C# from a Kernel-DSL model: a state enum AND a stateful domain class
/// whose guarded transition methods come straight from the DSL's transition table.
/// An ~8-line model expands into two ready-to-compile source files via Roslyn.
/// </summary>
public static class MainGenerator
{
    private const string NamespaceName = "Everapp.Generated";
    private const string GeneratedNote =
        "// GENERATED by MainGenerator from Resources/domain.dsl — do not edit.";

    public static void Main(string[] args)
    {
        // 1. Parse the DSL into an AST.
        ICharStream input = CharStreams.fromPath("Resources/domain.dsl");
        var lexer = new MyDSLLexer(input);
        var parser = new MyDSLParser(new CommonTokenStream(lexer));
        MyDSLParser.DomainContext domain = parser.domain();

        string domainName = domain.ID().GetText();              // "Agent"
        string enumName = $"{domainName}State";                 // "AgentState"
        string initialState = domain.states().ID(0).GetText();  // first declared state

        string outputDir = Path.Combine("bin", "generated-sources", "dsl", "Everapp", "Generated");
        Directory.CreateDirectory(outputDir);

        // 2. Derive the state enum via Roslyn SyntaxFactory.
        EnumMemberDeclarationSyntax[] enumMembers = domain.states().ID()
            .Select(id => EnumMemberDeclaration(Identifier(id.GetText())))
            .ToArray();

        EnumDeclarationSyntax enumDecl = EnumDeclaration(enumName)
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddMembers(enumMembers);

        WriteFile(enumDecl, Path.Combine(outputDir, $"{enumName}.cs"), includeSystemUsing: false);

        // 3. Derive the stateful domain class: one guarded method per transition.
        MemberDeclarationSyntax stateProperty = ParseMemberDeclaration(
            $"public {enumName} State {{ get; private set; }} = {enumName}.{initialState};")!;

        var transitionMethods = new List<MemberDeclarationSyntax>();
        foreach (MyDSLParser.TransitionContext t in domain.transitions().transition())
        {
            string action = t.actionName().GetText();
            string methodName = ToPascalCase(action);
            string from = t.fromState().GetText();
            string to = t.toState().GetText();

            MethodDeclarationSyntax method = MethodDeclaration(
                    PredefinedType(Token(SyntaxKind.VoidKeyword)),
                    Identifier(methodName))
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .WithBody(Block(
                    ParseStatement($"Require(State == {enumName}.{from}, \"{action}\");"),
                    ParseStatement($"State = {enumName}.{to};")));

            transitionMethods.Add(method);
        }

        // The one hand-shaped invariant the generator guarantees: no illegal transition.
        MemberDeclarationSyntax requireMethod = ParseMemberDeclaration(
            """
            private void Require(bool allowed, string action)
            {
                if (!allowed)
                {
                    throw new InvalidOperationException("Cannot " + action + " from state " + State);
                }
            }
            """)!;

        ClassDeclarationSyntax agentDecl = ClassDeclaration(domainName)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
            .AddMembers(stateProperty)
            .AddMembers(transitionMethods.ToArray())
            .AddMembers(requireMethod);

        WriteFile(agentDecl, Path.Combine(outputDir, $"{domainName}.cs"), includeSystemUsing: true);

        Console.WriteLine($"✅ Generated {enumName}.cs and {domainName}.cs in {Path.GetFullPath(outputDir)}");
    }

    private static void WriteFile(MemberDeclarationSyntax typeDecl, string filePath, bool includeSystemUsing)
    {
        FileScopedNamespaceDeclarationSyntax ns = FileScopedNamespaceDeclaration(ParseName(NamespaceName))
            .WithLeadingTrivia(Comment(GeneratedNote), CarriageReturnLineFeed);

        if (includeSystemUsing)
        {
            ns = ns.AddUsings(UsingDirective(IdentifierName("System")));
        }

        CompilationUnitSyntax unit = CompilationUnit()
            .AddMembers(ns.AddMembers(typeDecl))
            .NormalizeWhitespace();

        File.WriteAllText(filePath, unit.ToFullString() + Environment.NewLine);
    }

    private static string ToPascalCase(string identifier) =>
        string.IsNullOrEmpty(identifier)
            ? identifier
            : char.ToUpperInvariant(identifier[0]) + identifier[1..];
}
